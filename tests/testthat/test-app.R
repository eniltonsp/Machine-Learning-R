testthat::test_that("Shiny demo and filters work without a saved model", {
  withr::local_dir(project_root)
  app_env <- new.env(parent = globalenv())
  app <- source("app.R", local = app_env)$value
  testthat::expect_s3_class(app, "shiny.appobj")
  shiny::testServer(app_env$server, {
    session$setInputs(source = "demo", company = "All")
    testthat::expect_equal(nrow(dataset()), 600L)
    testthat::expect_equal(nrow(filtered()), 600L)
    testthat::expect_null(bundle())
    session$setInputs(company = "Demo Retail Alpha")
    testthat::expect_true(nrow(filtered()) > 0)
    testthat::expect_true(all(filtered()$company == "Demo Retail Alpha"))
    session$setInputs(company = "No matching company")
    testthat::expect_equal(nrow(filtered()), 0L)
    f <- tempfile(fileext = ".csv")
    writeLines(c("Empresa,Status,Data", "Example,Resolvido,2025-01-01", "Example,Respondida,2025-02-01"), f)
    session$setInputs(source = "upload", file = list(datapath = f), encoding = "UTF-8", delimiter = ",", backslash = FALSE, company = "All")
    testthat::expect_equal(nrow(dataset()), 2L)
    testthat::expect_equal(dataset()$status, c("Resolved", "Answered"))
    session$setInputs(dates = as.Date(c("2025-02-01", "2025-02-28")))
    testthat::expect_equal(nrow(filtered()), 1L)
  })
})
